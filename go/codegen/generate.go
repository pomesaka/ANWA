// Package codegen builds strict Go Handler interfaces from ANWA v0.2 manifests.
// The author-maintained anwa.json remains the sole source of truth.
package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"

	"github.com/pomesaka/ANWA/go/anwa"
)

const runtimeImport = "github.com/pomesaka/ANWA/go/anwa"

// Generate produces Go types, a compile-time ServerInterface, typed response
// variants, and adapters into the existing runtime. It rejects Go name
// collisions rather than silently producing ambiguous declarations.
func Generate(m anwa.Manifest, packageName string) ([]byte, error) {
	if err := m.Validate(); err != nil {
		return nil, err
	}
	if !validPackage(packageName) {
		return nil, fmt.Errorf("invalid Go package name %q", packageName)
	}
	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by anwa-codegen; DO NOT EDIT.\npackage %s\n\n", packageName)
	fmt.Fprintf(&out, "import (\n\t\"context\"\n\t\"fmt\"\n\t\"%s\"\n)\n\n", runtimeImport)

	registered := map[string]string{}
	register := func(name, source string) error {
		if previous, found := registered[name]; found {
			return fmt.Errorf("Go identifier %q collides between %s and %s", name, previous, source)
		}
		registered[name] = source
		return nil
	}
	for _, name := range sortedKeys(m.Definitions) {
		goName := exported(name)
		if err := register(goName, "$defs."+name); err != nil {
			return nil, err
		}
	}
	for _, ref := range sortedKeys(m.Interactions) {
		base := exported(ref)
		for _, suffix := range []string{"Input", "Output", "Request", "Response", "OK", "Failure", "Accepted", "ErrorCode"} {
			if err := register(base+suffix, ref); err != nil {
				return nil, err
			}
		}
	}
	for _, name := range sortedKeys(m.Definitions) {
		typ, err := schemaType(m.Definitions[name])
		if err != nil {
			return nil, fmt.Errorf("$defs.%s: %w", name, err)
		}
		fmt.Fprintf(&out, "type %s %s\n\n", exported(name), typ)
	}
	refs := sortedKeys(m.Interactions)
	for _, ref := range refs {
		spec := m.Interactions[ref]
		name := exported(ref)
		if spec.Input != nil {
			inputType, err := schemaType(spec.Input)
			if err != nil {
				return nil, fmt.Errorf("%s.input: %w", ref, err)
			}
			fmt.Fprintf(&out, "type %sInput %s\n\n", name, inputType)
		}
		outputType := "any"
		if spec.Output != nil {
			var err error
			outputType, err = schemaType(spec.Output)
			if err != nil {
				return nil, fmt.Errorf("%s.output: %w", ref, err)
			}
		}
		if spec.Kind != "event" {
			fmt.Fprintf(&out, "type %sOutput %s\n\n", name, outputType)
		}
		fmt.Fprintf(&out, "type %sRequest struct {\n", name)
		if spec.Input != nil {
			fmt.Fprintf(&out, " Input %sInput\n", name)
		}
		fmt.Fprintf(&out, " Caller *anwa.VerifiedCaller\n}\n\n")
		if spec.Kind == "event" {
			continue
		}

		fmt.Fprintf(&out, "type %sResponse interface {\n is%sResponse()\n toANWA() anwa.Response\n}\n\n", name, name)
		fmt.Fprintf(&out, "type %sOK struct {\n Value %sOutput\n Next []anwa.Next\n}\n", name, name)
		fmt.Fprintf(&out, "func (%sOK) is%sResponse() {}\n", name, name)
		fmt.Fprintf(&out, "func (r %sOK) toANWA() anwa.Response { return anwa.Reply(anwa.OK(r.Value), r.Next...) }\n\n", name)

		if len(spec.Errors) > 0 {
			fmt.Fprintf(&out, "type %sErrorCode string\nconst (\n", name)
			for _, code := range sortedKeys(spec.Errors) {
				fmt.Fprintf(&out, " %sError%s %sErrorCode = %q\n", name, exported(code), name, code)
			}
			fmt.Fprintf(&out, ")\n\n")
			fmt.Fprintf(&out, "type %sFailure struct {\n Code %sErrorCode\n Message string\n Details any\n Effects string\n Next []anwa.Next\n}\n", name, name)
			fmt.Fprintf(&out, "func (%sFailure) is%sResponse() {}\n", name, name)
			fmt.Fprintf(&out, "func (r %sFailure) toANWA() anwa.Response {\n", name)
			fmt.Fprintf(&out, " return anwa.Reply(anwa.Result{Error: &anwa.DomainError{Code: string(r.Code), Message: r.Message, Details: r.Details, Effects: r.Effects}}, r.Next...)\n}\n\n")
		}
		if spec.Kind == "action" {
			fmt.Fprintf(&out, "type %sAccepted struct {\n ExecutionID string\n Next []anwa.Next\n}\n", name)
			fmt.Fprintf(&out, "func (%sAccepted) is%sResponse() {}\n", name, name)
			fmt.Fprintf(&out, "func (r %sAccepted) toANWA() anwa.Response { return anwa.Accepted(r.ExecutionID, r.Next...) }\n\n", name)
		}
	}

	fmt.Fprintf(&out, "// ServerInterface must be implemented in full by the application.\n")
	fmt.Fprintf(&out, "type ServerInterface interface {\n")
	for _, ref := range refs {
		spec := m.Interactions[ref]
		name := exported(ref)
		if spec.Kind == "event" {
			fmt.Fprintf(&out, " %s(ctx context.Context, request %sRequest, cursor *int) (<-chan any, error)\n", name, name)
		} else {
			fmt.Fprintf(&out, " %s(ctx context.Context, request %sRequest) (%sResponse, error)\n", name, name, name)
			if spec.Guard != "" {
				fmt.Fprintf(&out, " %sOnDenied(ctx context.Context, request %sRequest, denied anwa.DomainError) ([]anwa.Next, error)\n", name, name)
			}
		}
	}
	fmt.Fprintf(&out, "}\n\n")
	fmt.Fprintf(&out, "// Handlers bridges the generated ServerInterface to the ANWA runtime.\n")
	fmt.Fprintf(&out, "// Config.Guards, Config.Discoverable, and explicit Config.Public remain app-owned.\n")
	fmt.Fprintf(&out, "func Handlers(server ServerInterface) map[string]anwa.Handler {\n")
	fmt.Fprintf(&out, " return map[string]anwa.Handler{\n")
	for _, ref := range refs {
		spec := m.Interactions[ref]
		name := exported(ref)
		fmt.Fprintf(&out, " %q: {\n", ref)
		if spec.Kind == "event" {
			fmt.Fprintf(&out, " Observe: func(ctx context.Context, args anwa.Args, cursor *int) (<-chan any, error) {\n")
			writeDecode(&out, name, spec.Input != nil, spec.Kind == "event")
			fmt.Fprintf(&out, " return server.%s(ctx, request, cursor)\n },\n", name)
		} else {
			fmt.Fprintf(&out, " Run: func(ctx context.Context, args anwa.Args) (anwa.Response, error) {\n")
			writeDecode(&out, name, spec.Input != nil)
			fmt.Fprintf(&out, " result, err := server.%s(ctx, request)\n", name)
			fmt.Fprintf(&out, " if err != nil { return anwa.Response{}, err }\n")
			fmt.Fprintf(&out, " if result == nil { return anwa.Response{}, fmt.Errorf(%q) }\n", ref+": nil response")
			fmt.Fprintf(&out, " return result.toANWA(), nil\n },\n")
			if spec.Guard != "" {
				fmt.Fprintf(&out, " OnDenied: func(ctx context.Context, args anwa.Args, denied anwa.DomainError) ([]anwa.Next, error) {\n")
				writeDecode(&out, name, spec.Input != nil, true)
				fmt.Fprintf(&out, " return server.%sOnDenied(ctx, request, denied)\n },\n", name)
			}
		}
		fmt.Fprintf(&out, " },\n")
	}
	fmt.Fprintf(&out, " }\n}\n")
	formatted, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated code: %w", err)
	}
	return formatted, nil
}

func writeDecode(out *strings.Builder, name string, hasInput bool, nilErrorReturn bool) {
	fmt.Fprintf(out, " request := %sRequest{Caller: args.Caller}\n", name)
	if hasInput {
		fmt.Fprintf(out, " if err := args.DecodeInput(&request.Input); err != nil {\\n")
		if nilErrorReturn {
			fmt.Fprintf(out, " return nil, err\\n")
		} else {
			fmt.Fprintf(out, " return anwa.Response{}, err\\n")
		}
		fmt.Fprintf(out, " }\\n")
	}
}

func schemaType(s *anwa.Schema) (string, error) {
	if s == nil {
		return "any", nil
	}
	if s.Ref != "" {
		return exported(strings.TrimPrefix(s.Ref, "#/$defs/")), nil
	}
	switch s.Type {
	case "string":
		return "string", nil
	case "integer":
		return "int64", nil
	case "number":
		return "float64", nil
	case "boolean":
		return "bool", nil
	case "null":
		return "any", nil
	case "array":
		item, err := schemaType(s.Items)
		if err != nil {
			return "", err
		}
		return "[]" + item, nil
	case "object":
		if len(s.Properties) == 0 || s.AdditionalProperties == nil {
			// Preserve unmodelled fields for an intentionally open object.
			return "map[string]any", nil
		}
		var fields strings.Builder
		used := make(map[string]string)
		for _, key := range sortedKeys(s.Properties) {
			goField := exported(key)
			if previous := used[goField]; previous != "" {
				return "", fmt.Errorf("field name collision: %q and %q", previous, key)
			}
			used[goField] = key
			typ, err := schemaType(s.Properties[key])
			if err != nil {
				return "", err
			}
			required := contains(s.Required, key)
			if !required && !strings.HasPrefix(typ, "[]") && !strings.HasPrefix(typ, "map[") && typ != "any" && !strings.HasPrefix(typ, "*") {
				typ = "*" + typ
			}
			tag := key
			if !required {
				tag += ",omitempty"
			}
			fmt.Fprintf(&fields, "%s %s `json:%q`\n", goField, typ, tag)
		}
		return "struct {\n" + fields.String() + "}", nil
	default:
		return "", fmt.Errorf("unsupported schema type: %q", s.Type)
	}
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for k := range values {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
func contains(xs []string, x string) bool {
	for _, item := range xs {
		if item == x {
			return true
		}
	}
	return false
}
func exported(s string) string {
	var result strings.Builder
	capNext := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			capNext = true
			continue
		}
		if capNext {
			result.WriteRune(unicode.ToUpper(r))
			capNext = false
		} else {
			result.WriteRune(r)
		}
	}
	value := result.String()
	if value == "" || unicode.IsDigit([]rune(value)[0]) {
		return "X" + value
	}
	return value
}
func validPackage(name string) bool {
	if name == "" || name == "_" {
		return false
	}
	for index, r := range name {
		if (index == 0 && !unicode.IsLetter(r) && r != '_') ||
			(index > 0 && !unicode.IsLetter(r) && !unicode.IsDigit(r) && r != '_') {
			return false
		}
	}
	return true
}
